#!/usr/bin/env python3
"""inventory.py - writes INVENTORY.md from findings.json (summary of the inventory of codgen)."""
import collections, json, os
here = os.path.dirname(os.path.abspath(__file__))
fj = json.load(open(os.path.join(here, 'findings.json')))
f = fj['functions']
conf = {k: v for k, v in f.items() if v['pairing'] == 'confirmed'}
none = sorted(k for k, v in f.items() if v['pairing'] == 'none')
exact = sorted(k for k, v in conf.items() if v['level'].startswith('exact'))
donly = sorted(k for k, v in conf.items() if v['audit']['difference_class'].startswith('D only'))
other = sorted(k for k, v in conf.items() if v['audit']['difference_class'] == 'other differences')
L = []
L.append('# codgen inventory (status of the analysis)')
L.append('')
L.append('Generated from findings.json by inventory.py. Method and limits: see classification_method and the notes below.')
L.append('')
L.append('## Pairings')
L.append('')
L.append('- functions of our codgen: %d' % len(f))
L.append('- confirmed with a counterpart in /lib/codgen: %d' % len(conf))
L.append('- without counterpart on our side: %s' % ', '.join('`%s`' % n for n in none))
L.append('- original functions without counterpart on our side: `0x4868` (forwarder of main, main-wrapper-01), `0x6fca` and `0x854c` (dead code, quirk table)')
L.append('- code coverage: every instruction of our codgen belongs to a function; in the original only the start code (0x0-0x28) lies outside the pairings, and the continuation of rdsym (0x1aae) belongs to rdsym')
L.append('')
L.append('## Identical')
L.append('')
L.append('Identical under metric strict-1 (the same instruction sequence, only addresses masked): %d functions: %s' % (len(exact), ', '.join('`%s`' % n for n in exact)))
L.append('')
L.append('## Only D1-D14 (pattern-verified)')
L.append('')
L.append('%d functions: every differing instruction matches a D pattern (D1, D2, D3, D5, D6, D7, D8, D10, D11, D13). The order of the instructions is not part of this check. D4, D9, D12 and D14 are not separable by these patterns.' % len(donly))
L.append('')
L.append('## D1-D14 and real differences')
L.append('')
L.append('%d functions with real differences (the D part is not separated from them): %s' % (len(other), ', '.join('`%s`' % n for n in other)))
L.append('')
L.append('## Real differences (findings)')
L.append('')
for it in fj['findings_pending']:
    L.append('- `%s` (%s): %s' % (it['id'], it.get('status', '-'), it.get('detail', '')[:160]))
L.append('')
L.append('## Limits')
L.append('')
L.append('- The D classes are assigned by patterns over the instruction forms, not by a separate test with the old cc. Layout and order are not compared.')
L.append('- Pairings with header or string evidence were checked on the body only partly (see audit and the review notes in findings.json).')
L.append('- The original is stripped; its function starts come from call targets and the instruction after a ret.')
open(os.path.join(here, 'INVENTORY.md'), 'w').write('\n'.join(L) + '\n')
print('written INVENTORY.md')
