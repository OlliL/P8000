"""Derive epu_data.py: run epuprobe1.py, epuprobe2.py (writes tab.json) in a work
directory, then python3 epugen.py there."""
import json,re,sys
t=json.load(open('tab.json'))
def parse(txt):
    n,o=txt.split('\t'); ops=o.split(',')
    shape=[]; regs=[]
    for x in ops:
        m=re.fullmatch(r'(@?)([fr])(\d+)',x)
        shape.append(m.group(1)+m.group(2)); regs.append(int(m.group(3)))
    return n,tuple(shape),regs
groups={}
for k,v in t.items():
    w=bytes.fromhex(k)
    if len(w)!=4: continue
    cands=[parse(x) for x in v]
    # canonical name: prefer the one with a suffix s/d/x only if unique
    names=[c[0] for c in cands]
    if len(set(names))>1:
        # reg-reg ambiguous: pick bare base
        names=sorted(names,key=len)
    n=names[0]
    c=[x for x in cands if x[0]==n][0]
    groups.setdefault((n,c[1]),[]).append((int.from_bytes(w[:2],'big'),int.from_bytes(w[2:],'big'),c[2]))
out=[]
for (n,shape),L in sorted(groups.items()):
    w1=[x[0] for x in L]; w2=[x[1] for x in L]
    # fields: for each operand, bits changing
    nop=len(shape)
    fields=[]
    for i in range(nop):
        bits1=bits2=0
        for a in L:
            for b in L:
                if all(a[2][j]==b[2][j] for j in range(nop) if j!=i) and a[2][i]!=b[2][i]:
                    bits1|=a[0]^b[0]; bits2|=a[1]^b[1]
        fields.append((bits1,bits2))
    var1=0;var2=0
    for a in L: var1|=a[0]^L[0][0]; var2|=a[1]^L[0][1]
    # variable bits must be covered by fields
    cov1=0;cov2=0
    for f in fields: cov1|=f[0];cov2|=f[1]
    if (var1&~cov1) or (var2&~cov2): print('uncovered',n,shape,hex(var1),hex(cov1),hex(var2),hex(cov2),file=sys.stderr)
    # check each field is in single word
    fs=[]
    for f in fields:
        if f[0] and not f[1]: fs.append((1,f[0]))
        elif f[1] and not f[0]: fs.append((2,f[1]))
        else: print('split field',n,shape,f,file=sys.stderr); fs.append((0,0))
    m1=0xFFFF&~var1; m2=0xFFFF&~var2
    out.append((m1,L[0][0]&m1,m2,L[0][1]&m2,n,list(shape),fs))
with open('epu_data.py','w') as f:
    f.write("# generated by epugen.py from as -f oracle: EPU templates\n# (mask1, val1, mask2, val2, mnemonic, operand shapes, [(word, mask)] per operand)\nEPU = [\n")
    for o in out: f.write("    %r,\n"%(o,))
    f.write("]\n")
print(len(out))
